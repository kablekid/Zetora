// Generates supabase/seed.sql from demo-content.mjs.
//   node supabase/seed/generate.mjs
// The output is deterministic (stable UUIDs), so re-running the seed replaces
// the previous demo rows instead of duplicating them.
import { createHash } from 'node:crypto';
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { subjects, exams, welcomeNotification } from './demo-content.mjs';

const here = dirname(fileURLToPath(import.meta.url));

function uuid(name) {
  const h = createHash('sha1').update('zetora-demo:' + name).digest('hex');
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-5${h.slice(13, 16)}-a${h.slice(17, 20)}-${h.slice(20, 32)}`;
}
const q = (s) => (s == null ? 'null' : `'${String(s).replace(/'/g, "''")}'`);
const arr = (a) => (a.length ? `array[${a.map(q).join(', ')}]::text[]` : `'{}'::text[]`);
const words = (html) => html.replace(/<[^>]+>/g, ' ').split(/\s+/).filter(Boolean).length;

const out = [];
const push = (s) => out.push(s);

push(`-- =============================================================================
-- Zetora DEMO seed (generated by supabase/seed/generate.mjs — do not edit by hand)
--
-- Sample content for development. It is NOT an official or verified Ethiopian
-- syllabus. Everything here is flagged is_demo = true; remove it all from
-- Admin → Settings → "Remove demo content", or run:
--   delete from public.subjects where is_demo; delete from public.exams where is_demo;
-- Safe to re-run: previous demo rows are replaced.
-- =============================================================================
begin;
select set_config('app.skip_notifications', 'on', true);

delete from public.exams     where is_demo;
delete from public.quizzes   where is_demo;
delete from public.questions where is_demo;
delete from public.subjects  where is_demo;
`);

subjects.forEach((s, si) => {
  const sid = uuid(`subject:${s.slug}`);
  push(`insert into public.subjects (id, slug, title, description, icon, color, position, is_published, is_demo)
values (${q(sid)}, ${q(s.slug)}, ${q(s.title)}, ${q(s.description)}, ${q(s.icon)}, ${q(s.color)}, ${si + 1}, true, true);`);

  s.units.forEach((u, ui) => {
    const uid = uuid(`unit:${s.slug}:${ui}`);
    push(`insert into public.units (id, subject_id, number, position, title, description, introduction, objectives, key_concepts, estimated_minutes, is_published, is_demo)
values (${q(uid)}, ${q(sid)}, ${ui + 1}, ${ui + 1}, ${q(u.title)}, ${q(u.description)}, ${q(u.introduction)}, ${arr(u.objectives)}, ${arr(u.concepts)}, ${u.minutes}, true, true);`);

    u.topics.forEach((t, ti) => {
      push(`insert into public.topics (id, unit_id, title, position) values (${q(uuid(`topic:${s.slug}:${ui}:${t}`))}, ${q(uid)}, ${q(t)}, ${ti + 1});`);
    });

    if (u.summary) {
      push(`insert into public.summaries (unit_id, content_html, status, word_count, published_at)
values (${q(uid)}, ${q(u.summary)}, 'published', ${words(u.summary)}, now());`);
    }

    if (u.quiz) {
      const qz = u.quiz;
      const quizId = uuid(`quiz:${s.slug}:${ui}`);
      push(`insert into public.quizzes (id, title, description, subject_id, unit_id, mode, time_limit_minutes, pass_percentage, shuffle_questions, is_published, is_demo)
values (${q(quizId)}, ${q(qz.title)}, ${q(qz.mode === 'practice' ? 'Instant feedback after every question. Demo content.' : 'Timed. Answers are revealed after you submit. Demo content.')}, ${q(sid)}, ${q(uid)}, ${q(qz.mode)}, ${qz.time ?? 'null'}, ${qz.pass}, ${qz.mode === 'exam'}, true, true);`);

      qz.questions.forEach((qu, qi) => {
        const qid = uuid(`q:${s.slug}:${ui}:${qi}`);
        const topicId = qu.topic ? q(uuid(`topic:${s.slug}:${ui}:${qu.topic}`)) : 'null';
        push(`insert into public.questions (id, subject_id, unit_id, topic_id, type, body, explanation, accepted_answers, difficulty, is_demo)
values (${q(qid)}, ${q(sid)}, ${q(uid)}, ${topicId}, ${q(qu.type)}, ${q(qu.body)}, ${q(qu.explanation)}, ${arr(qu.accepted_answers ?? [])}, ${q(qu.difficulty)}, true);`);
        qu.options.forEach((o, oi) => {
          push(`insert into public.question_options (id, question_id, body, is_correct, position) values (${q(uuid(`opt:${qid}:${oi}`))}, ${q(qid)}, ${q(o.body)}, ${o.is_correct}, ${oi + 1});`);
        });
        push(`insert into public.quiz_questions (quiz_id, question_id, position) values (${q(quizId)}, ${q(qid)}, ${qi + 1});`);
      });
    }
  });
});

exams.forEach((e) => {
  const eid = uuid(`exam:${e.title}`);
  const sid = e.subject ? q(uuid(`subject:${e.subject}`)) : 'null';
  push(`insert into public.exams (id, title, description, kind, subject_id, question_count, duration_minutes, pass_percentage, is_published, is_demo)
values (${q(eid)}, ${q(e.title)}, ${q(e.description)}, ${q(e.kind)}, ${sid}, ${e.count}, ${e.minutes}, ${e.pass}, true, true);`);
  (e.units ?? []).forEach(([slug, idx]) => {
    push(`insert into public.exam_units (exam_id, unit_id) values (${q(eid)}, ${q(uuid(`unit:${slug}:${idx}`))});`);
  });
});

push(`
insert into public.notifications (id, kind, title, body, link)
values (${q(uuid('notification:welcome'))}, 'announcement', ${q(welcomeNotification.title)}, ${q(welcomeNotification.body)}, ${q(welcomeNotification.link)})
on conflict (id) do nothing;

commit;
`);

writeFileSync(join(here, '..', 'seed.sql'), out.join('\n') + '\n');
console.log(`Wrote supabase/seed.sql (${out.length} statements)`);
